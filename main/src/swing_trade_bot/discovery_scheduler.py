"""Automated paper-only discovery pipeline scheduler."""

from __future__ import annotations

import argparse
import csv
from collections.abc import Sequence
from dataclasses import asdict, dataclass
from datetime import date
from pathlib import Path
from typing import Literal

from swing_trade_bot.discovery_engine import (
    DiscoveryEngine,
    SourceMention,
    WatchlistRow,
    load_candidates,
    load_financial_health,
    load_mentions,
    theme_momentum_score,
    write_watchlist_reports,
)
from swing_trade_bot.mention_extractor import (
    ExtractedMention,
    merge_mentions,
    read_discovery_mentions_csv,
    write_discovery_mentions_csv,
)
from swing_trade_bot.news_feed_collector import NewsFeedCollector
from swing_trade_bot.youtube_feed_collector import YouTubeFeedCollector


SchedulerMode = Literal["daily", "weekly", "monthly"]
SUMMARY_COLUMNS = (
    "symbol",
    "mention_count_30d",
    "source_count",
    "confluence_score",
    "theme_momentum_score",
    "watchlist_status",
    "composite_score",
)


@dataclass(frozen=True, slots=True)
class DiscoveryPipelineResult:
    """Files generated by one scheduler run."""

    youtube_mentions_path: Path
    news_mentions_path: Path
    discovery_mentions_path: Path
    watchlist_csv_path: Path
    watchlist_json_path: Path
    discovery_summary_path: Path


class DiscoveryScheduler:
    """Run feed collection, mention merging, discovery scoring, and summary output."""

    def __init__(self, *, paper_trade_mode: bool = True) -> None:
        if not paper_trade_mode:
            raise ValueError("DiscoveryScheduler requires paper_trade_mode=True")
        self.paper_trade_mode = paper_trade_mode

    def run(
        self,
        *,
        youtube_feed: Path,
        news_feed: Path,
        candidates_path: Path,
        financial_health_path: Path,
        output_dir: Path,
        mode: SchedulerMode = "daily",
        as_of: date | None = None,
    ) -> DiscoveryPipelineResult:
        """Execute the full paper-only discovery pipeline."""
        _validate_mode(mode)
        as_of = as_of or date.today()
        output_dir.mkdir(parents=True, exist_ok=True)

        youtube_path = output_dir / "youtube_mentions.csv"
        news_path = output_dir / "news_mentions.csv"
        discovery_path = output_dir / "discovery_mentions.csv"
        summary_path = output_dir / "discovery_summary.csv"

        YouTubeFeedCollector(paper_trade_mode=True).write_mentions(youtube_feed, youtube_path)
        NewsFeedCollector(paper_trade_mode=True).write_mentions(news_feed, news_path)

        merged = merge_mentions(
            [
                *read_discovery_mentions_csv(youtube_path),
                *read_discovery_mentions_csv(news_path),
                *read_discovery_mentions_csv(discovery_path),
            ]
        )
        write_discovery_mentions_csv(discovery_path, merged)

        rows = DiscoveryEngine(paper_trade_mode=True).evaluate(
            load_candidates(candidates_path),
            load_mentions(discovery_path),
            load_financial_health(financial_health_path),
            as_of=as_of,
        )
        watchlist_csv, watchlist_json = write_watchlist_reports(output_dir, rows)
        write_discovery_summary(summary_path, rows, load_mentions(discovery_path), as_of=as_of)
        return DiscoveryPipelineResult(
            youtube_mentions_path=youtube_path,
            news_mentions_path=news_path,
            discovery_mentions_path=discovery_path,
            watchlist_csv_path=watchlist_csv,
            watchlist_json_path=watchlist_json,
            discovery_summary_path=summary_path,
        )


def write_discovery_summary(
    path: Path,
    rows: Sequence[WatchlistRow],
    mentions: Sequence[SourceMention],
    *,
    as_of: date,
) -> Path:
    """Write discovery_summary.csv monitoring report."""
    with path.open("w", newline="", encoding="utf-8") as output_file:
        writer = csv.DictWriter(output_file, fieldnames=SUMMARY_COLUMNS)
        writer.writeheader()
        for row in rows:
            recent = [
                mention
                for mention in mentions
                if mention.underlying_symbol.upper() == row.underlying_symbol
                and 0 <= (as_of - mention.mentioned_on).days <= 30
            ]
            writer.writerow(
                {
                    "symbol": row.underlying_symbol,
                    "mention_count_30d": len(recent),
                    "source_count": row.source_count,
                    "confluence_score": row.source_confluence_score,
                    "theme_momentum_score": row.theme_momentum_score
                    or theme_momentum_score(tuple(row.themes.split(";")), recent, as_of=as_of),
                    "watchlist_status": row.watchlist_status,
                    "composite_score": row.composite_score,
                }
            )
    return path


def merge_mention_files(output_path: Path, input_paths: Sequence[Path]) -> Path:
    """Merge mention CSVs and remove duplicates by symbol, source, and date."""
    mentions: list[ExtractedMention] = []
    for input_path in input_paths:
        mentions.extend(read_discovery_mentions_csv(input_path))
    return write_discovery_mentions_csv(output_path, merge_mentions(mentions))


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the automated paper-only discovery pipeline")
    parser.add_argument("--mode", choices=["daily", "weekly", "monthly"], default="daily")
    parser.add_argument("--youtube-feed", type=Path, required=True)
    parser.add_argument("--news-feed", type=Path, required=True)
    parser.add_argument("--candidates", type=Path, required=True)
    parser.add_argument("--financial-health", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("."))
    parser.add_argument("--as-of", type=date.fromisoformat, default=date.today())
    args = parser.parse_args()

    result = DiscoveryScheduler(paper_trade_mode=True).run(
        youtube_feed=args.youtube_feed,
        news_feed=args.news_feed,
        candidates_path=args.candidates,
        financial_health_path=args.financial_health,
        output_dir=args.output_dir,
        mode=args.mode,
        as_of=args.as_of,
    )
    print(_format_result(result))


def _validate_mode(mode: SchedulerMode) -> None:
    if mode not in {"daily", "weekly", "monthly"}:
        raise ValueError("mode must be daily, weekly, or monthly")


def _format_result(result: DiscoveryPipelineResult) -> str:
    lines = ["Discovery pipeline complete:"]
    for key, value in asdict(result).items():
        lines.append(f"- {key}: {value}")
    return "\n".join(lines)


if __name__ == "__main__":
    main()
